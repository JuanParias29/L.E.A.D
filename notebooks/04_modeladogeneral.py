def crear_intervencion(
    indice,
    fecha,
    tipo,
    decaimiento=0.7
):
    intervencion = pd.Series(
        0.0,
        index=indice
    )

    posicion = indice.get_loc(fecha)

    if tipo == "AO":
        # Efecto únicamente en la semana detectada
        intervencion.iloc[posicion] = 1.0

    elif tipo == "LS":
        # Cambio permanente desde la fecha detectada
        intervencion.iloc[posicion:] = 1.0

    elif tipo == "TC":
        # Efecto transitorio con reducción exponencial
        longitud = len(indice) - posicion

        intervencion.iloc[posicion:] = (
            decaimiento **
            np.arange(longitud)
        )

    return intervencion

