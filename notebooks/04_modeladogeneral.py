def procesar_producto(
    id_producto,
    datos_producto,
    df_quiebres,
    fecha_corte
):
    nombre_producto = (
        datos_producto["Producto"]
        .dropna()
        .iloc[0]
    )

    # Crear serie semanal
    semanal = (
        datos_producto
        .set_index("FECHA")
        .resample("W-MON")
        .agg({
            "Facturado": "sum",
            "BackOrder": "sum",
            "VlrUnitario": "mean"
        })
    )

    semanal["demanda_observada"] = (
        semanal["Facturado"] +
        semanal["BackOrder"]
    )

    # Completar el precio
    semanal["VlrUnitario"] = (
        semanal["VlrUnitario"]
        .interpolate()
        .ffill()
        .bfill()
    )

    # Requerir suficientes semanas
    if len(semanal) < 70:
        raise ValueError(
            f"Solo tiene {len(semanal)} semanas"
        )

    # Crear dummies de eventos
    for nombre in [
        "Vacaciones",
        "SemanaSanta",
        "RuedaNegocios",
        "Feria"
    ]:
        semanal[f"Evento_{nombre}"] = 0.0

    for evento in eventos_globales:

        if evento["fecha"] in semanal.index:
            semanal.loc[
                evento["fecha"],
                f'Evento_{evento["nombre"]}'
            ] = 1.0

    # Crear dummy de quiebre
    semanal["Evento_QuiebreInventario"] = 0.0

    quiebres_producto = df_quiebres[
        df_quiebres["IDProductos"].astype(str)
        == str(id_producto)
    ]

    for fecha_semana in semanal.index:

        año = fecha_semana.isocalendar().year
        numero_semana = fecha_semana.isocalendar().week

        # Excluir semanas finales
        if numero_semana in [52, 53]:
            continue

        inicio_semana = (
            fecha_semana -
            pd.Timedelta(weeks=1)
        )

        existe_quiebre = (
            (
                quiebres_producto["FechaInicial"]
                <= fecha_semana
            )
            &
            (
                quiebres_producto["FechaFinal"]
                > inicio_semana
            )
        ).any()

        if existe_quiebre:
            semanal.loc[
                fecha_semana,
                "Evento_QuiebreInventario"
            ] = 1.0

    columnas_eventos = [
        "Evento_Vacaciones",
        "Evento_SemanaSanta",
        "Evento_RuedaNegocios",
        "Evento_Feria"
    ]

    # --------------------------------------------------
    # Imputación contrafactual de los quiebres
    # --------------------------------------------------

    y_observada = semanal[
        "demanda_observada"
    ].astype(float)

    mascara_quiebre = (
        semanal["Evento_QuiebreInventario"] == 1
    )

    # Eliminar eventos constantes
    eventos_imputacion = [
        columna
        for columna in columnas_eventos
        if semanal[columna].nunique() > 1
    ]

    X_imputacion = (
        semanal[eventos_imputacion].astype(float)
        if eventos_imputacion
        else None
    )

    resultado_imputacion = impute_stockout_demand(
        y_observada,
        mascara_quiebre,
        exog=X_imputacion,
    )
    demanda_contrafactual = resultado_imputacion.counterfactual

    # Mantener al menos la demanda observada
    semanal["demanda_real"] = y_observada

    semanal.loc[
        mascara_quiebre,
        "demanda_real"
    ] = np.maximum(
        y_observada.loc[mascara_quiebre],
        demanda_contrafactual.loc[mascara_quiebre]
    )

    # Precio rezagado
    semanal["Precio_lag1"] = (
        semanal["VlrUnitario"].shift(1)
    )

    semanal = semanal.dropna(
        subset=["Precio_lag1"]
    )

    # --------------------------------------------------
    # Entrenamiento y prueba
    # --------------------------------------------------

    train = semanal[
        semanal.index <= fecha_corte
    ]

    test = semanal[
        semanal.index > fecha_corte
    ]

    if len(train) < 40 or len(test) < 8:
        raise ValueError(
            "No tiene suficientes datos de entrenamiento o prueba"
        )

    y_train = train["demanda_real"]
    y_test = test["demanda_real"]

    variables_base = (
        columnas_eventos +
        ["Evento_QuiebreInventario"]
    )

    # Eliminar variables constantes en entrenamiento
    variables_base = [
        columna
        for columna in variables_base
        if train[columna].nunique() > 1
    ]

    X_train_base = train[
        variables_base
    ].astype(float)

    X_test_base = test[
        variables_base
    ].astype(float)

    # Estandarizar precio con entrenamiento
    media_precio = train["Precio_lag1"].mean()
    desviacion_precio = train["Precio_lag1"].std()

    modelos = []

    # --------------------------------------------------
    # Modelo sin precio
    # --------------------------------------------------

    modelo_sin_precio = fit_sarimax(
        y_train,
        exog=X_train_base,
        order=(0, 0, 1),
        seasonal_order=(0, 0, 0, 0),
        trend="c",
        enforce_stationarity=False,
        enforce_invertibility=False,
    )

    pred_sin_precio = forecast_sarimax(
        modelo_sin_precio,
        len(y_test),
        exog=X_test_base,
        index=y_test.index,
    )

    modelos.append({
        "modelo": "SARIMAX sin precio",
        "prediccion": pred_sin_precio,
        "aic": modelo_sin_precio.aic
    })

    # --------------------------------------------------
    # Modelo con precio
    # --------------------------------------------------

    if (
        pd.notna(desviacion_precio)
        and desviacion_precio > 0
    ):
        semanal["Precio_std"] = (
            semanal["Precio_lag1"] -
            media_precio
        ) / desviacion_precio

        train = semanal[
            semanal.index <= fecha_corte
        ]

        test = semanal[
            semanal.index > fecha_corte
        ]

        variables_precio = (
            variables_base +
            ["Precio_std"]
        )

        X_train_precio = train[
            variables_precio
        ].astype(float)

        X_test_precio = test[
            variables_precio
        ].astype(float)

        modelo_con_precio = fit_sarimax(
            y_train,
            exog=X_train_precio,
            order=(0, 0, 1),
            seasonal_order=(0, 0, 0, 0),
            trend="c",
            enforce_stationarity=False,
            enforce_invertibility=False,
        )

        pred_con_precio = forecast_sarimax(
            modelo_con_precio,
            len(y_test),
            exog=X_test_precio,
            index=y_test.index,
        )

        modelos.append({
            "modelo": "SARIMAX con precio",
            "prediccion": pred_con_precio,
            "aic": modelo_con_precio.aic
        })

    # --------------------------------------------------
    # Guardar predicciones
    # --------------------------------------------------

    resultados = []

    for resultado_modelo in modelos:

        prediccion = resultado_modelo[
            "prediccion"
        ]

        for fecha in y_test.index:
            resultados.append({
                "IDProducto": id_producto,
                "Producto": nombre_producto,
                "FECHA": fecha,
                "modelo": resultado_modelo["modelo"],
                "real": y_test.loc[fecha],
                "prediccion": prediccion.loc[fecha],
                "AIC": resultado_modelo["aic"]
            })

    return resultados

