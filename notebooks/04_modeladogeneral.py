"""### Descomposición Clásica (Estacionalidad, Tendencia, Variabilidad)"""

from statsmodels.tsa.seasonal import seasonal_decompose
from statsmodels.graphics.tsaplots import plot_acf, plot_pacf

# Crear la demanda real
df_productos["FECHA"] = pd.to_datetime(df_productos["FECHA"])
df_productos["demanda_real"] = df_productos["BackOrder"] + df_productos["Facturado"]

for producto in df_productos["Producto"].unique():

    # Construir la serie semanal del producto
    serie = (
        df_productos[df_productos["Producto"] == producto]
        .set_index("FECHA")["demanda_real"]
        .resample("W-MON")
        .sum()
        .asfreq("W-MON", fill_value=0)
    )

    # Descomposición clásica con estacionalidad anual de 52 semanas
    descomposicion = seasonal_decompose(
        serie,
        model="additive",
        period=52,
        extrapolate_trend="freq"
    )

    # Graficar serie, tendencia, estacionalidad y residuos
    figura = descomposicion.plot()
    figura.set_size_inches(14, 10)
    figura.suptitle(
        f"Descomposición clásica semanal: {producto}",
        fontsize=16,
        y=1.02
    )
    plt.tight_layout()
    plt.show()

    # Graficar ACF y PACF
    fig, axes = plt.subplots(2, 1, figsize=(14, 9))

    plot_acf(
        serie,
        lags=52,
        ax=axes[0],
        alpha=0.05
    )
    axes[0].set_title(f"ACF de la demanda semanal: {producto}")
    axes[0].set_xlabel("Rezago en semanas")
    axes[0].set_ylabel("Autocorrelación")
    axes[0].grid(True, alpha=0.3)

    plot_pacf(
        serie,
        lags=52,
        ax=axes[1],
        alpha=0.05,
        method="ywm"
    )
    axes[1].set_title(f"PACF de la demanda semanal: {producto}")
    axes[1].set_xlabel("Rezago en semanas")
    axes[1].set_ylabel("Autocorrelación parcial")
    axes[1].grid(True, alpha=0.3)

    plt.tight_layout()
    plt.show()

