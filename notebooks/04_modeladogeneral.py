def metricas_grupo(grupo):

    error = (
        grupo["real"] -
        grupo["prediccion"]
    )

    return pd.Series({
        "MAE": np.abs(error).mean(),
        "RMSE": np.sqrt(
            np.mean(error ** 2)
        ),
        "WAPE_%": (
            np.abs(error).sum()
            / np.abs(grupo["real"]).sum()
        ) * 100,
        "Sesgo": error.mean(),
        "Demanda_total": grupo["real"].sum()
    })

