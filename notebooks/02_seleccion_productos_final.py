"""### Clasificación ABC-XYZ para Productos Nacionales"""

import pandas as pd
import numpy as np

# Generar la nueva variable 'demanda_observada' para df_nacionales
df_nacionales['demanda_observada'] = df_nacionales['Facturado'] + df_nacionales['BackOrder']

# --- ABC: por VentaTotal--
venta_por_producto_nacionales = df_nacionales.groupby('Producto', observed=False)['VentaTotal'].sum().sort_values(ascending=False)
venta_pct_nacionales = venta_por_producto_nacionales / venta_por_producto_nacionales.sum() * 100
venta_acum_nacionales = venta_pct_nacionales.cumsum()

def clasif_abc(acum):
   if acum <= 80:
       return 'A'
   elif acum <= 95:
       return 'B'
   else:
       return 'C'

abc_nacionales = venta_acum_nacionales.apply(clasif_abc)

# --- XYZ: por variabilidad de la demanda semanal (incluye semanas sin venta = intermitencia) ---
# Asegurarse de que 'FECHA' es datetime en df_nacionales
if not pd.api.types.is_datetime64_any_dtype(df_nacionales['FECHA']):
    df_nacionales['FECHA'] = pd.to_datetime(df_nacionales['FECHA'], errors='coerce')

# Eliminar filas con fechas nulas que puedan haber surgido de la conversión
df_nacionales_cleaned_dates = df_nacionales.dropna(subset=['FECHA']).copy()

full_weeks_nacionales = pd.date_range(df_nacionales_cleaned_dates['FECHA'].min(), df_nacionales_cleaned_dates['FECHA'].max(), freq='W')

weekly_nacionales = (
   df_nacionales_cleaned_dates.groupby([pd.Grouper(key='FECHA', freq='W'), 'Producto'], observed=False)['demanda_observada']
   .sum()
   .unstack(fill_value=0)
)
weekly_nacionales = weekly_nacionales.reindex(full_weeks_nacionales, fill_value=0)

mean_w_nacionales = weekly_nacionales.mean()
std_w_nacionales = weekly_nacionales.std()
cv_nacionales = (std_w_nacionales / mean_w_nacionales).replace([np.inf, -np.inf], np.nan)

def clasif_xyz(c):
   if pd.isna(c):
       return 'Z'
   if c <= 0.5:
       return 'X'
   elif c <= 1.0:
       return 'Y'
   else:
       return 'Z'

xyz_nacionales = cv_nacionales.apply(clasif_xyz)

resumen_nacionales = pd.DataFrame({
   'VentaTotal': venta_por_producto_nacionales,
   'PctVenta': venta_pct_nacionales,
   'PctAcum': venta_acum_nacionales,
   'ABC': abc_nacionales,
   'DemandaSemanalProm': mean_w_nacionales,
   'CV': cv_nacionales,
   'XYZ': xyz_nacionales,
}).dropna(subset=['ABC'])

resumen_nacionales['Clase'] = resumen_nacionales['ABC'] + resumen_nacionales['XYZ']
resumen_nacionales = resumen_nacionales.sort_values('VentaTotal', ascending=False)

# Save to a new CSV file
resumen_nacionales.to_csv('clasificacion_abc_xyz_nacionales.csv', sep=';')

print("Clasificación ABC-XYZ para productos nacionales generada y guardada en 'clasificacion_abc_xyz_nacionales.csv'.")
display(resumen_nacionales.head())

