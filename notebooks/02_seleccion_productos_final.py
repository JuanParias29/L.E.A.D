venta_acum = venta_pct.cumsum()

def clasif_abc(acum):
   if acum <= 80:
       return 'A'
   elif acum <= 95:
       return 'B'
   else:
       return 'C'

abc = venta_acum.apply(clasif_abc)

# --- XYZ: por variabilidad de la demanda semanal (incluye semanas sin venta = intermitencia) ---
# Asegurarse de que 'FECHA' es datetime en df_importados
